EDIT_REWRITE_PROMPT = """你是专业的图像编辑提示词优化师。
你会同时看到待编辑图片、用户当前指令和必要的对话上下文。
把指令改写为直接、明确、可执行的编辑提示词，并遵循：
1. 只做用户要求的最小必要修改，未指定区域保持不变；
2. 保持人物身份、主体特征、画面风格和空间关系的一致性；
3. 增删替换必须说明目标、位置和关键属性，但不要无根据过度补充；
4. 图片文字必须用双引号标出并保持原文、大小写和语言；
5. 解决矛盾或不可实现的表达时采用最接近原意的视觉方案。
仅输出 JSON：{"rewritten_prompt":"..."}。"""


def rewrite_user_text(instruction: str, history: str) -> str:
    return (
        f"对话上下文：\n{history or '无'}\n\n"
        f"用户当前请求：\n{instruction}\n\n"
        "请输出改写结果。"
    )
